// The canvas is a blueprint. Only painted pixels support the walls in the simulation.
function star(a,x,y,r,tips,inner,color){
  const points=Array.from({length:tips*2},(_,i)=>{
    const t=-Math.PI/2+i*Math.PI/tips, radius=i%2?inner:r;
    return [x+Math.cos(t)*radius,y+Math.sin(t)*radius];
  });
  a.poly(color,points);
}

